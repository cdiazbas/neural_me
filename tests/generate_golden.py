
import torch
import os
import sys

# Ensure we can import neural_me
sys.path.append(os.path.join(os.path.dirname(__file__), "../src"))

from neural_me.physics.milne_eddington import MilneEddington

def generate_golden_data(output_path="tests/golden_data.pt", batch_size=1024, n_lambda=128):
    """
    Generates reference 'golden' data from the current validated model.
    """
    print("Initializing model for golden data generation...")
    # Initialize model
    # Use standard line parameters (Fe I 6301.5 as in verification)
    # line_vec = [6301.5012, 2.5, 4.67e-13 * 2.5**2] # Simplified metadata if needed, 
    # but strictly MilneEddington class might need explicit nlinea if it uses paramLine inside.
    # Looking at milne_eddington.py, if nlinea is None, it doesn't init self.param by default unless passed.
    # But stokesSyn expects 'param' argument.
    # In baseline verification: ME = MilneEddington(nlinea)
    # nlinea was 5 (for Fe I 6301 and 6302 pair usually? or index?) 
    # Let's check baseline_verification.ipynb or utils logic for nlinea.
    # Actually, paramLine(nlinea) returns the atomic data. 
    # In baseline_verification, nlinea=4 is used.
    
    # We will use nlinea=4 (Fe I 6301.5) as standard.
    nlinea = 4
    model = MilneEddington(nlinea=nlinea)
    
    # Generate synthetic parameters
    print(f"Generating synthetic parameters (batch_size={batch_size})...")
    torch.manual_seed(42) # For reproducibility
    
    # Params: [B, gamma, xi, vlos, eta0, a, ddop, S_0, S_1]
    # Range validation taken roughly from typical solar values
    B = torch.rand(batch_size) * 3.0 # 0-3 kG (note model expects kG input logic? Model takes B_in and multiplies by 1e3? 
    # In forward(): B = params[:,0][:,None]*1e3. So input param 0 is in kG? 
    # Let's verify forward() implementation.
    # Yes: B = params[:,0][:,None]*1e3. So inputs are ~ kG.
    
    gamma = torch.rand(batch_size) * 180.0 * (torch.pi / 180.0) # 0-180 deg in rad
    xi = torch.rand(batch_size) * 180.0 * (torch.pi / 180.0) # 0-180 deg in rad
    vlos = (torch.rand(batch_size) - 0.5) * 10.0 # -5 to 5 km/s
    eta0 = torch.rand(batch_size) * 10.0 + 1.0 # 1 to 11
    a = torch.rand(batch_size) * 1.0 # 0 to 1
    ddop = torch.rand(batch_size) * 0.05 + 0.02 # 0.02 to 0.07 A
    S_0 = torch.rand(batch_size) * 0.5 + 0.5 
    S_1 = torch.rand(batch_size) * 0.5 + 0.5
    
    # Stack into (batch, 9)
    # Order: [B, gamma, xi, vlos, eta0, a, ddop, S_0, S_1]
    params = torch.stack([B, gamma, xi, vlos, eta0, a, ddop, S_0, S_1], dim=1)
    
    # Wavelength grid
    # Centered around 6301.5 + some offset
    wl_center = 6301.5012
    wl = torch.linspace(wl_center - 1.0, wl_center + 1.0, n_lambda).unsqueeze(0).repeat(batch_size, 1)
    
    print("Running forward pass...")
    # Run model
    # forward(self, params, wl, nlinea=None)
    with torch.no_grad():
        I, Q, U, V = model(params, wl)
    
    # Stack outputs: (batch, 4, n_lambda)
    # The return of forward is I, Q, U, V as (batch, n_lambda)
    # Let's stack them to save conveniently
    stokes = torch.stack([I, Q, U, V], dim=1)
    
    print(f"Saving golden data to {output_path}...")
    data = {
        "params": params,
        "wl": wl,
        "stokes": stokes,
        "nlinea": nlinea,
        "description": "Golden data generated by verified optimized model (Level 2 opt)"
    }
    
    torch.save(data, output_path)
    print("Done!")

if __name__ == "__main__":
    generate_golden_data()
